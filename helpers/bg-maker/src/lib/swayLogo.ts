const f = (n: number) => +n.toFixed(4);

// The logo centred at (cx, cy), `height` px tall
export function logoSvg(cx: number, cy: number, height: number, colors: LogoColors): string {
  const k = height / LOGO_BOX.h;
  const tx = cx - (LOGO_BOX.w * k) / 2 - LOGO_BOX.x * k;
  const ty = cy - height / 2 - LOGO_BOX.y * k;
  const out = [`<g transform="matrix(${f(k)} 0 0 ${f(k)} ${f(tx)} ${f(ty)})">`];
  for (const { part } of LOGO_PARTS) for (const d of PATHS[part]) out.push(`<path fill="${colors[part]}" d="${d}"/>`);
  out.push("</g>");
  return out.join("");
}
